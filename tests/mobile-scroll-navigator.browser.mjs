import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/USER/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base = process.env.TEST_BASE_URL || process.argv[2] || 'http://127.0.0.1:3000';
const readyBy = Date.now() + 120000;
while (true) {
  try {
    const response = await fetch(base + '/api/health', { signal: AbortSignal.timeout(3000) });
    if (response.ok) break;
  } catch {}
  assert.ok(Date.now() < readyBy, 'Start the LAWPEX dev server before running browser checks');
  await new Promise(resolve => setTimeout(resolve, 1000));
}
console.log('Starting mobile navigator browser checks');
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, timeout: 60000, args: ['--no-proxy-server'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
page.setDefaultTimeout(45000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const slider = page.getByRole('slider', { name: 'Document position', exact: true });
const start = async () => {
  const box = await slider.locator('[data-scroll-thumb]').boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
};
const drag = async fraction => {
  const box = await slider.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + 22 + fraction * (box.height - 44), { steps: 5 });
  await page.waitForTimeout(150);
};
const progress = () => page.evaluate(() => scrollY / (document.documentElement.scrollHeight - innerHeight));
try {
  await page.goto(base + '/case-law/case/case-001', { waitUntil: 'commit', timeout: 90000 });
  console.log('Case page response received');
  await page.getByRole('button', { name: '1. Ratio decidendi', exact: true }).waitFor({ timeout: 120000 });
  await page.waitForTimeout(100);
  assert.equal(await slider.count(), 0, 'ratio lists must not show the reader handle');
  for (const label of ['2. Case digest', '3. Principles of law', '4. Authorities & notes']) {
    await page.getByRole('button', { name: label, exact: true }).click();
    await slider.waitFor({ state: 'hidden' });
  }
  await page.getByRole('button', { name: '5. Read the whole case', exact: true }).click({ timeout: 120000 });
  await page.locator('[data-report-page-number="7"]').waitFor();
  await slider.waitFor();
  console.log('Case reader and draggable navigator loaded');
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await start();
  await drag(0.55);
  assert.ok(Math.abs(await progress() - 0.55) < 0.03, 'drag maps directly to document position');
  assert.match(await slider.getAttribute('aria-valuetext'), /Page \d+ of \d+/);
  assert.equal(await page.getByRole('status').filter({ hasText: /Page \d+ of \d+/ }).count(), 1);
  await drag(0.2);
  assert.ok(Math.abs(await progress() - 0.2) < 0.03, 'dragging upward moves back');
  await page.mouse.up();
  const released = await page.evaluate(() => scrollY);
  await page.waitForTimeout(180);
  assert.ok(Math.abs((await page.evaluate(() => scrollY)) - released) < 3, 'release stops immediately');
  await slider.focus();
  await page.keyboard.press('End');
  assert.ok(await progress() > 0.99);
  await page.keyboard.press('Home');
  assert.ok(await progress() < 0.01);
  await page.keyboard.press('PageDown');
  assert.ok((await page.evaluate(() => scrollY)) > 400);
  await start();
  await drag(0.35);
  await slider.dispatchEvent('pointercancel');
  const cancelled = await page.evaluate(() => scrollY);
  await drag(0.8);
  assert.ok(Math.abs((await page.evaluate(() => scrollY)) - cancelled) < 3, 'cancel stops the gesture');
  await page.mouse.up();
  await slider.evaluate(element => element.blur());
  console.log('Drag, keyboard and cancellation passed');
  const nav = await slider.boundingBox();
  assert.ok(nav.x >= 358 && nav.x + nav.width <= 390, 'whole-case navigation must be on the right edge');
  const caseTextEdges = await page.locator('[data-case-report-id] p').evaluateAll(elements => elements.map(element => element.getBoundingClientRect()).filter(rect => rect.top < innerHeight && rect.bottom > 150).map(rect => rect.right));
  assert.ok(caseTextEdges.length && Math.max(...caseTextEdges) <= nav.x, 'the right-side handle must not cover judgment text');
  await mkdir('tmp/mobile-scroll-navigator', { recursive: true });
  await page.screenshot({ path: 'tmp/mobile-scroll-navigator/case-mobile.png', animations: 'disabled' });
  await page.getByRole('button', { name: '2. Case digest', exact: true }).click();
  await slider.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '5. Read the whole case', exact: true }).click();
  await slider.waitFor();
  await page.evaluate(() => {
    const reader = document.createElement('div');
    reader.id = 'scroll-reader-fixture';
    reader.style.cssText = 'position:fixed;top:120px;left:90px;right:70px;height:400px;overflow-y:auto;background:white;z-index:10';
    reader.innerHTML = '<div style="height:50000px">Document text</div>';
    document.body.append(reader);
    window.dispatchEvent(new Event('resize'));
  });
  await page.waitForTimeout(100);
  const behind = await page.evaluate(() => scrollY);
  await start();
  await drag(0.5);
  assert.ok((await page.locator('#scroll-reader-fixture').evaluate(element => element.scrollTop)) > 24000);
  assert.equal(await page.evaluate(() => scrollY), behind, 'scroll embedded readers, not background');
  assert.match(await slider.getAttribute('aria-valuetext'), /50%/);
  await page.mouse.up();
  await page.locator('#scroll-reader-fixture').evaluate(element => element.remove());
  console.log('Embedded reader passed');
  await page.setViewportSize({ width: 360, height: 560 });
  await page.waitForTimeout(100);
  const shortNav = await slider.boundingBox();
  assert.ok(shortNav.x >= 328 && shortNav.y >= 64 && shortNav.y + shortNav.height <= 464, 'short viewports keep the right-side handle clear of header and launcher');
  await page.setViewportSize({ width: 320, height: 640 });
  await page.screenshot({ path: 'tmp/mobile-scroll-navigator/narrow-mobile.png', animations: 'disabled' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await start();
  await page.evaluate(() => document.querySelector('a[href="/case-law"]').click());
  await page.waitForURL('**/case-law');
  await page.mouse.up();
  await page.waitForFunction(() => scrollY < 3);
  await page.waitForTimeout(200);
  assert.ok((await page.evaluate(() => scrollY)) < 3, 'route change cancels drag');
  await slider.waitFor({ state: 'hidden' });
  console.log('Mobile layouts and route cleanup passed');
  for (const path of ['/', '/case-law', '/court-rules', '/court-rules/supreme-court', '/nigerian-laws', '/nigerian-laws/federation']) {
    await page.goto(base + path, { waitUntil: 'commit', timeout: 90000 });
    await page.locator('main h1').first().waitFor({ timeout: 120000 });
    assert.equal(await slider.count(), 0, 'landing and listing pages must not show the handle: ' + path);
  }
  await page.goto(base + '/nigerian-laws/federation/cama-2020', { waitUntil: 'commit', timeout: 90000 });
  await page.locator('[data-page-number]').first().waitFor({ timeout: 45000 });
  await slider.waitFor();
  const readerSearch = page.getByRole('textbox', { name: /^Search / }).first();
  await readerSearch.focus();
  await page.waitForTimeout(100);
  assert.equal(await slider.isVisible(), true, 'the handle must remain visible when a reader search field retains focus');
  const touchBefore = await page.evaluate(() => scrollY);
  const touchThumb = await slider.locator('[data-scroll-thumb]').boundingBox();
  const touchRail = await slider.boundingBox();
  const touch = await page.context().newCDPSession(page);
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: touchThumb.x + touchThumb.width / 2, y: touchThumb.y + touchThumb.height / 2 }] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: touchRail.x + touchRail.width / 2, y: touchRail.y + 22 + 0.35 * (touchRail.height - 44) }] });
  await page.waitForTimeout(150);
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await touch.detach();
  assert.ok((await page.evaluate(() => scrollY)) > touchBefore + 500, 'finger dragging must work while the search field retains focus');
  assert.equal(await slider.isVisible(), true, 'touch release must not hide the handle');
  await readerSearch.evaluate(element => element.blur());
  await start();
  await drag(0.45);
  assert.match(await slider.getAttribute('aria-valuetext'), /Page \d+ of \d+/);
  await page.mouse.up();
  const lawNav = await slider.boundingBox();
  const ai = await page.getByRole('link', { name: 'Open the Ai Draft Wizard', exact: true }).boundingBox();
  assert.ok(lawNav.y + lawNav.height <= ai.y - 8);
  const edges = await page.locator('[data-page-number] p').evaluateAll(elements => elements.map(element => element.getBoundingClientRect()).filter(rect => rect.top < innerHeight && rect.bottom > 64).map(rect => rect.right));
  assert.ok(edges.length && Math.max(...edges) <= lawNav.x, 'fits law reader margin');
  await page.screenshot({ path: 'tmp/mobile-scroll-navigator/law-mobile.png', animations: 'disabled' });
  await page.goto(base + '/court-rules/supreme-court/supreme-court-rules-2024', { waitUntil: 'commit', timeout: 90000 });
  await page.locator('[data-page-number]').first().waitFor({ timeout: 90000 });
  await slider.waitFor();
  await start();
  await drag(0.5);
  await page.mouse.up();
  assert.ok((await page.evaluate(() => scrollY)) > 600, 'long rule books support fast navigation');
  assert.match(await slider.getAttribute('aria-valuetext'), /Page \d+ of \d+/);
  const rulesNav = await slider.boundingBox();
  assert.ok(rulesNav.x >= 288 && rulesNav.x + rulesNav.width <= 320, 'rule-book navigation is also on the right');
  await page.screenshot({ path: 'tmp/mobile-scroll-navigator/rules-mobile.png', animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await slider.waitFor({ state: 'hidden' });
  assert.deepEqual(errors, []);
  console.log('Drag, page hints, keyboard, cancellation, embedded readers, mobile layouts, route cleanup, desktop visibility passed');
} catch (error) {
  console.error(error);
  await mkdir('tmp/mobile-scroll-navigator', { recursive: true });
  await page.screenshot({ path: 'tmp/mobile-scroll-navigator/failure.png', timeout: 10000 }).catch(() => {});
  console.error('Browser location:', page.url());
  console.error('Page errors:', errors);
  throw error;
} finally {
  await browser.close();
}
