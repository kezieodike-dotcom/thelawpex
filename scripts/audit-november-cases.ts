import { readFile, writeFile } from 'node:fs/promises';
import { auditCaseRatioCitations, inspectRatioSources } from '../src/components/modules/CaseLawView.tsx';
import { NOVEMBER_CASES } from '../src/data/novemberCases.ts';

const report = [
  '# November 2026 Case Import Audit',
  '',
  'Every reference below is generated from the current LAWPEX pages and A-G paragraph labels. Quotations are located only in identified judicial opinions, never in the headnote itself.',
  '',
];
const diagnostics = [];
const verifiedMetadata = [];
let failures = 0;

const replaceHeadnoteAttributions = (text: string, attributions: string[]) => {
  const ratioIndex = text.search(/\bRATIO(?:\(S\))? DECIDENDI\b/i);
  if (ratioIndex < 0) return text;
  const leadingIndex = text.slice(ratioIndex).search(/[A-Z][A-Z .'-]+,\s*J\.?\s*S\.?\s*C\.?[\s\S]{0,90}\(Delivering\s+the\s+(?:Leading\s+Judgment|Lead\s+Ruling)\)/i);
  if (leadingIndex < 0) return text;
  const end = ratioIndex + leadingIndex;
  let cursor = 0;
  const headnote = text.slice(ratioIndex, end).replace(/^Per\s+[^\r\n]+$/gim, (line) => attributions[cursor++] ?? line);
  return text.slice(0, ratioIndex) + headnote + text.slice(end);
};

for (const metadata of NOVEMBER_CASES) {
  const sourceUrl = new URL(`../src/data/judgments/${metadata.id}.json`, import.meta.url);
  const source = JSON.parse(await readFile(sourceUrl, 'utf8'));
  const judgment = { ...metadata, ...source };
  const inspection = inspectRatioSources(judgment);
  const ratios = auditCaseRatioCitations(judgment);
  const updatedRatios = metadata.ratioDecidendi.map((text, index) =>
    text.replace(/\nPer\s+[\s\S]*$/i, `\n${ratios[index]?.attribution ?? ''}`),
  );
  const ratioSourceReferences = ratios.map(ratio => ({
    page: ratio.evidence?.start.pageNumber ?? 0,
    paragraph: ratio.evidence?.start.label ?? '',
  }));

  report.push(`## ${metadata.title} ${metadata.citation}`, '', `${inspection.pages.length + 1} LAWPEX pages; ${ratios.length} supplied ratio passages.`, '', '| Ratio | Source reference | Coverage | Status |', '| --- | --- | --- | --- |');
  ratios.forEach((ratio, index) => {
    const status = ratio.evidence ? 'VERIFIED' : 'UNRESOLVED';
    if (!ratio.evidence) failures += 1;
    report.push(`| ${index + 1} | ${ratio.attribution || 'UNRESOLVED'} | ${ratio.evidence ? `${(ratio.evidence.coverage * 100).toFixed(1)}%` : '0%'} | ${status} |`);
  });
  report.push('');

  const updatedSource = {
    ...source,
    fullJudgmentText: replaceHeadnoteAttributions(source.fullJudgmentText, ratios.map(ratio => ratio.attribution)),
  };
  diagnostics.push({ id: metadata.id, ratios, targets: inspection.targets });
  verifiedMetadata.push({
    ...metadata,
    reportFormatVersion: 'lawpex-reviewed-v1',
    ratioSourceReferences,
    ratioDecidendi: updatedRatios,
  });
  if (process.argv.includes('--write')) await writeFile(sourceUrl, `${JSON.stringify(updatedSource, null, 2)}\n`);
}

await writeFile(new URL('../tmp/november-case-diagnostics.json', import.meta.url), JSON.stringify(diagnostics, null, 2));
await writeFile(new URL('../doc/case-imports/november-2026/ratio-audit.md', import.meta.url), report.join('\n'));

if (failures) throw new Error(`${failures} ratio passages still require source reconciliation`);
if (process.argv.includes('--write')) {
  await writeFile(new URL('../src/data/novemberCases.ts', import.meta.url), `import { CaseLaw } from '../types';\n\n// Generated by scripts/import-november-cases.mjs and verified by audit-november-cases.ts.\nexport const NOVEMBER_CASES = JSON.parse(${JSON.stringify(JSON.stringify(verifiedMetadata))}) as CaseLaw[];\n`);
}
