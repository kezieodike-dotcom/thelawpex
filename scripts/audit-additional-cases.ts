import { readFile, writeFile } from 'node:fs/promises';
import { ADDITIONAL_CASES } from '../src/data/additionalCases.ts';
import { auditCaseRatioCitations, inspectRatioSources } from '../src/components/modules/CaseLawView.tsx';

const report = ['# October 2026 Case Import Audit', '', 'References use the current LAWPEX pages and attached A-G paragraph labels, not the DOCX page numbers. Every quotation is checked against the judicial opinion, never against its own headnote.', ''];
let failures = 0;
const diagnostics = [];
const verifiedMetadata = [];
for (const metadata of ADDITIONAL_CASES) {
  const source = JSON.parse(await readFile(new URL(`../src/data/judgments/${metadata.id}.json`, import.meta.url), 'utf8'));
  const judgment = {...metadata, ...source};
  const inspection = inspectRatioSources(judgment);
  const ratios = auditCaseRatioCitations(judgment);
  report.push(`## ${metadata.title} ${metadata.citation}`, '', `${inspection.pages.length + 1} pages; ${ratios.length} ratios.`, '', '| Ratio | Source reference | Text coverage |', '| --- | --- | --- |');
  for (const [i, ratio] of ratios.entries()) {
    if (!ratio.evidence) failures++;
    report.push(`| ${i + 1} | ${ratio.attribution || 'UNRESOLVED'} | ${ratio.evidence ? (ratio.evidence.coverage * 100).toFixed(1) + '%' : 'UNRESOLVED'} |`);
    console.log(`${metadata.id} ${i + 1}: ${ratio.evidence ? ratio.attribution : 'UNRESOLVED'}`);
  }
  diagnostics.push({id: metadata.id, ratios, targets: inspection.targets});
  verifiedMetadata.push({...metadata, ratioDecidendi: metadata.ratioDecidendi.map((text, i) => text.replace(/\nPer\s[\s\S]*$/i, `\n${ratios[i]?.attribution || ''}`))});
  report.push('');
}
await writeFile(new URL('../tmp/additional-case-diagnostics.json', import.meta.url), JSON.stringify(diagnostics));
await writeFile(new URL('../doc/case-imports/october-2026/ratio-audit.md', import.meta.url), report.join('\n'));
if (failures) throw new Error(`${failures} ratios need source review`);
if (process.argv.includes('--write-metadata')) {
  await writeFile(new URL('../src/data/additionalCases.ts', import.meta.url), `import { CaseLaw } from '../types';\n\n// Generated by import-additional-cases.mjs and audited by audit-additional-cases.ts.\nexport const ADDITIONAL_CASES: CaseLaw[] = ${JSON.stringify(verifiedMetadata, null, 2)};\n`);
}
